async function getRecentHistory(db, token, platform, contactId) {
  const MAX_MESSAGES = 40;
  const summaryRow = await db.prepare(
    "SELECT summary, summarized_up_to_id FROM session_summary WHERE token = ? AND platform = ? AND contact_id = ?"
  ).bind(token, platform, contactId).first();
  const summary = summaryRow?.summary || "";
  const { results } = await db.prepare(
    `SELECT id, role, content, created_at FROM chat_history
     WHERE token = ? AND platform = ? AND contact_id = ?
     ORDER BY created_at DESC LIMIT ?`
  ).bind(token, platform, contactId, MAX_MESSAGES + 10).all();
  if (!results || results.length === 0) {
    return { messages: [], summary, hoursAgo: 0 };
  }
  const allMessages = results.reverse();
  let hoursAgo = 0;
  for (let i = allMessages.length - 1; i >= 0; i--) {
    if (allMessages[i].role === "user") {
      hoursAgo = Math.floor((Date.now() / 1e3 - allMessages[i].created_at) / 3600);
      break;
    }
  }
  let messages;
  if (allMessages.length <= MAX_MESSAGES) {
    messages = allMessages.map((m) => ({ role: m.role, content: m.content, created_at: m.created_at }));
  } else {
    messages = allMessages.slice(allMessages.length - MAX_MESSAGES).map((m) => ({
      role: m.role,
      content: m.content,
      created_at: m.created_at
    }));
  }
  return { messages, summary, hoursAgo };
}
